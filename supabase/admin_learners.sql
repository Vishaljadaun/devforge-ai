  ) then
    raise exception 'Admin access required' using errcode = '42501';
  end if;

  select count(*) into v_total
    from auth.users u
    where v_search = '' or position(v_search in lower(coalesce(u.email, ''))) > 0;

  select coalesce(jsonb_agg(jsonb_build_object(
      'user_id', d.id,
      'email', d.email,
      'registered_at', d.created_at,
      'last_sign_in_at', d.last_sign_in_at,
      'last_progress_save_at', d.last_progress_save_at,
      'completed_topics', d.completed_topics,
      'progress_percent', round(100.0 * d.completed_topics / 323)::integer,
      'is_admin', d.is_admin
    ) order by d.sort_sign_in desc, d.created_at desc, d.id desc), '[]'::jsonb)
    into v_learners
    from (
      select
        u.id,
        u.email,
        u.created_at,
        u.last_sign_in_at,
        uw.updated_at as last_progress_save_at,
        coalesce(u.last_sign_in_at, u.created_at) as sort_sign_in,
        exists(select 1 from public.content_admins ca where ca.user_id = u.id) as is_admin,
        least(323, (
          select count(distinct topic.value)
            from jsonb_array_elements_text(
              case when jsonb_typeof(uw.payload->'doneTopics') = 'array'
                then uw.payload->'doneTopics' else '[]'::jsonb end
            ) as topic(value)
            where topic.value = any(v_valid_topics)
        ))::integer as completed_topics
      from auth.users u
      left join public.user_workspaces uw on uw.user_id = u.id
      where v_search = '' or position(v_search in lower(coalesce(u.email, ''))) > 0
      order by coalesce(u.last_sign_in_at, u.created_at) desc, u.created_at desc, u.id desc
      limit v_page_size offset (v_page - 1) * v_page_size
    ) d;

